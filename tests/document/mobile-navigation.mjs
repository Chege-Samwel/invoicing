import fs from 'node:fs';
import { JSDOM } from 'jsdom';
const root = new URL('../../', import.meta.url);
const read = p => fs.readFileSync(new URL(p, root), 'utf8');
const source = read('assets/users/js/general.js');
const header = read('application/modules/users/views/parts/header.php');
const css = read('assets/users/css/anvoice.css');
let pass = 0, fail = 0;
function check(name, ok) { if (ok) pass++; else { fail++; console.log(' FAIL ' + name); } }
const dom = new JSDOM('<button id="av-nav-toggle" aria-expanded="false"><span id="av-nav-toggle-label"></span></button><div class="left-col"><div id="main-menu"><button class="av-nav-close">Close</button><a href="/one">One</a><a href="/two">Two</a></div></div><main>Content</main>', {runScripts:'outside-only', url:'https://example.test'});
const w = dom.window; let narrow = true;
w.matchMedia = () => ({ matches: narrow });
w.lang = { show_main_menu:'Show menu', hide_main_menu:'Hide menu' };
const start = source.lastIndexOf('(function () {\n    // nav-state.js');
const end = source.indexOf('\n})();', start) + '\n})();'.length;
w.eval(source.slice(start, end));
const btn = w.document.querySelector('#av-nav-toggle'), close = w.document.querySelector('.av-nav-close');
btn.click();
check('mobile drawer opens and moves focus inside', w.document.body.classList.contains('av-nav-open') && btn.getAttribute('aria-expanded') === 'true' && w.document.activeElement === close);
w.document.dispatchEvent(new w.KeyboardEvent('keydown', {key:'Tab', shiftKey:true, bubbles:true, cancelable:true}));
check('keyboard focus wraps within drawer', w.document.activeElement.textContent === 'Two');
w.document.dispatchEvent(new w.KeyboardEvent('keydown', {key:'Escape', bubbles:true}));
check('Escape closes drawer and restores focus', !w.document.body.classList.contains('av-nav-open') && w.document.activeElement === btn && btn.getAttribute('aria-expanded') === 'false');
btn.click(); close.click();
check('close button closes drawer and restores focus', !w.document.body.classList.contains('av-nav-open') && w.document.activeElement === btn);
narrow = false; w.dispatchEvent(new w.Event('resize')); btn.click();
narrow = true; w.dispatchEvent(new w.Event('resize')); narrow = false; w.dispatchEvent(new w.Event('resize'));
check('desktop menu choice survives breakpoint changes', btn.getAttribute('aria-expanded') === 'false');
check('main menu button is outside the account collapse', header.indexOf('id="av-nav-toggle"') < header.indexOf('id="myNavbar"'));
check('mobile account menu has an accessible toggle', /aria-controls="myNavbar" aria-expanded="false"/.test(header));
check('mobile account menu collapses and opens', css.includes('.navbar-collapse.collapse.in') && css.includes('max-height: calc(100vh - 58px)'));
check('wide content has local horizontal scrolling', css.includes('.right-side .table-responsive, .right-side .table-container'));
dom.window.close();
console.log(`${fail ? fail + ' FAILED' : 'all pass'}  (${pass} passed)`); process.exit(fail ? 1 : 0);
