async function render(path, varBlock, extra = '') {
  const php = new PhpNode();
  let out = '';
  php.addEventListener('output', e => { out += e.detail[0]; });
  await php.run('<?php @mkdir("/app",0777,TRUE);');
  await php.writeFile('/app/view.php', fs.readFileSync(ROOT + path));
  await php.writeFile('/app/tpl.php', '<div class="adoc">invoice body</div>');
  await php.writeFile('/app/run.php', PRELUDE + extra + varBlock + "\nob_start(); include '/app/view.php'; echo ob_get_clean();\n");
  await php.run('<?php require "/app/run.php";');
  return out;
}

